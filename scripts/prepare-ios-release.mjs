#!/usr/bin/env node
/**
 * Prepares an iOS-stream release by writing the app's version into
 * apps/ios/App/App.xcodeproj/project.pbxproj.
 *
 * iOS releases on its own cadence, independent of the server (`vX.Y.Z`) and Android
 * (`android-vX.Y.Z`) streams — foundational/PLAN_35_PHASE_NATIVE_RELEASE_STREAMS.md. iOS is not
 * distributed yet (no Apple Developer enrollment; unsigned Simulator builds only), so this stream's
 * value today is structural: it stops iOS rebuilding on every server tag and gives it real version
 * numbers for a future TestFlight/App Store release.
 *
 * Usage:
 *   1. On a branch:  pnpm prepare-ios-release ios-v1.8.1
 *      Commit, PR, merge.
 *   2. Tag the merge commit and push it:  git tag ios-v1.8.1 && git push origin ios-v1.8.1
 *      This triggers ios-build.yml (Simulator build -> the iOS GitHub Release).
 *
 * `MARKETING_VERSION` is `CFBundleShortVersionString` (the user-facing version);
 * `CURRENT_PROJECT_VERSION` is `CFBundleVersion` and must increase every submission, so it's
 * derived monotonically from the version (MAJOR*10000 + MINOR*100 + PATCH) and the script refuses
 * to lower it. Values are regex-replaced in place (the project file is generated by Xcode and must
 * keep its formatting), the same approach scripts/prepare-release.mjs takes with package.json.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const repoRoot = path.resolve(fileURLToPath(import.meta.url), '../..')

const tag = process.argv[2]
if (!tag || !/^ios-v\d+\.\d+\.\d+$/.test(tag)) {
  console.error(
    'Usage: node scripts/prepare-ios-release.mjs ios-vX.Y.Z (stable releases only, no -rc/-beta suffix)'
  )
  process.exit(1)
}
const version = tag.slice('ios-v'.length)

const pbxprojPath = path.join(repoRoot, 'apps/ios/App/App.xcodeproj/project.pbxproj')
const contents = readFileSync(pbxprojPath, 'utf8')

// X.Y.Z -> X*10000 + Y*100 + Z. Monotonic across releases (no rollover within a major until
// minor 100, which this project will never reach).
const [major, minor, patch] = version.split('.').map(Number)
const buildNumber = major * 10000 + minor * 100 + patch

const marketingField = /MARKETING_VERSION = [^;]+;/
const buildField = /CURRENT_PROJECT_VERSION = [^;]+;/
if (!marketingField.test(contents) || !buildField.test(contents)) {
  console.error(
    `Could not find MARKETING_VERSION / CURRENT_PROJECT_VERSION in ${pbxprojPath} — ` +
      'did the Xcode project layout change? Update this script if so.'
  )
  process.exit(1)
}

const currentBuild = currentBuildNumber(contents)
if (currentBuild !== null && buildNumber <= currentBuild) {
  console.error(
    `Refusing to write ${tag}: its build number ${buildNumber} is not greater than the current ` +
      `${currentBuild}. App Store submission requires a strictly increasing build number — pick a ` +
      'higher iOS version.'
  )
  process.exit(1)
}

// Replace every occurrence (Debug + Release build configurations).
const updated = contents
  .replace(new RegExp(marketingField.source, 'g'), `MARKETING_VERSION = ${version};`)
  .replace(new RegExp(buildField.source, 'g'), `CURRENT_PROJECT_VERSION = ${buildNumber};`)
writeFileSync(pbxprojPath, updated)
console.log(
  `Updated apps/ios/App/App.xcodeproj/project.pbxproj -> v${version} (build ${buildNumber})`
)
console.log(
  `\nDone. Review the diff, then commit/PR/merge, tag the merge commit \`${tag}\`, and push it.`
)

/**
 * The highest CURRENT_PROJECT_VERSION currently in the project file, or null if none parse.
 *
 * @param {string} pbxproj
 * @returns {number | null}
 */
function currentBuildNumber(pbxproj) {
  const values = [...pbxproj.matchAll(/CURRENT_PROJECT_VERSION = (\d+);/g)].map((m) => Number(m[1]))
  if (values.length === 0) return null
  return Math.max(...values)
}
